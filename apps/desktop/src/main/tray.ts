/**
 * E2E-only: measurement of "tray click → fully-painted popover" for
 * the perf baseline / regression spec. Two operating modes,
 * determined by the live tray-window state:
 *
 *   - cold: no tray window exists. The bridge creates it, attaches
 *     event listeners, shows it, waits for the renderer's resize to
 *     stabilize. Mirrors today's first-click production flow.
 *   - prewarmed: a tray window already exists, created at boot by
 *     `prewarmTrayWindow()`. The bridge skips construction and just
 *     times `show() → paint`. Mirrors the optimized production flow.
 *
 * Checkpoint set is the same shape across both modes — fields that
 * don't apply in `prewarmed` (windowCreated, domReady, etc.) come
 * back as `null` so spec consumers can print one uniform table.
 */
export async function measureTrayFirstPaintForE2E(options: {
  stableMs?: number;
  /**
   * Per-measurement deadline. The default must comfortably exceed the
   * ~10s scheduler-starvation stretches the VS2026 `windows-latest`
   * runner image exhibits (see docs/solutions/
   * 2026-06-13-windows-vs2026-runner-image-e2e-flakes.md §4): in the
   * 2026-07-16 recurrence, boot + first paint ran at normal speed and
   * the seeded-content reflow — normally ~60ms behind the first
   * measurement — stalled just past the then-10s budget, so a
   * starved-but-working renderer timed out by construction. A genuine
   * regression (the reflow never happens) still times out, just
   * slower.
   */
  timeoutMs?: number;
  /**
   * Minimum content height (DIP) the popover must reach before its size
   * is accepted as "stable". Defaults to 0 (no gate).
   *
   * The "no resize for stableMs" heuristic alone is unsound when the
   * popover's final height depends on an async reflow that lands AFTER a
   * quiet period: a seeded last-snap preview is fetched over IPC and its
   * image decoded via pwrsnap-capture://, so the renderer first measures
   * the empty/text-only height (~248) and only later re-measures to the
   * full seeded height (~634). When that second reflow arrives more than
   * stableMs after the first measurement — routine on the slower VS2026
   * runner image — the bare heuristic breaks at ~248, the empty-tray
   * band. Callers that know they seeded content pass the expected floor
   * so the measurement waits for the real content instead of sampling
   * the transient empty state. A height that never reaches the floor
   * times out (`timedOut: true`) — a genuine regression still fails.
   */
  minStableHeight?: number;
} = {}): Promise<{
  mode: "cold" | "prewarmed";
  windowCreated: number | null;
  domReady: number | null;
  didFinishLoad: number | null;
  readyToShow: number | null;
  isVisible: number | null;
  firstResize: number | null;
  stableResize: number | null;
  resizeApplied: number | null;
  finalContentHeight: number | null;
  requestedContentHeight: number | null;
  mainReportedContentHeight: number | null;
  resizeCount: number;
  timedOut: boolean;
}> {
  const stableMs = options.stableMs ?? 300;
  const timeoutMs = options.timeoutMs ?? 30_000;
  const minStableHeight = options.minStableHeight ?? 0;

  const alreadyExists = trayWindow !== null && !trayWindow.isDestroyed();
  const mode: "cold" | "prewarmed" = alreadyExists ? "prewarmed" : "cold";

  if (alreadyExists && trayWindow!.isVisible()) {
    throw new Error("measureTrayFirstPaintForE2E: tray window already visible; hide first");
  }

  const t0 = performance.now();
  const mark = (): number => Math.round((performance.now() - t0) * 100) / 100;

  // Probe listener for the renderer's resize channel. Observes the
  // production listener (wireTrayResizeChannel) without interfering.
  // In the prewarmed case the renderer has already posted its initial
  // measurement during pre-warm; no new resize is expected unless the
  // content changes between pre-warm and show.
  let firstResize: number | null = null;
  let lastResizeAt = 0;
  let resizeCount = 0;
  const probe = (_event: Electron.IpcMainEvent, payload: unknown): void => {
    if (
      payload === null ||
      typeof payload !== "object" ||
      typeof (payload as { height: unknown }).height !== "number" ||
      !Number.isFinite((payload as { height: number }).height)
    ) {
      return;
    }
    resizeCount += 1;
    if (firstResize === null) firstResize = mark();
    lastResizeAt = performance.now();
  };
  // Belt-and-suspenders: wire the production channel in case the
  // bridge runs before installTray() / prewarmTrayWindow() did
  // (E2E mode skips installTray). Idempotent.
  wireTrayResizeChannel();
  ipcMain.on(TRAY_RESIZE_CHANNEL, probe);

  let windowCreated: number | null = null;
  let domReady: number | null = null;
  let didFinishLoad: number | null = null;
  let readyToShow: number | null = null;

  const window = ensureTrayWindow();
  if (!alreadyExists) {
    windowCreated = mark();
    // `ensureTrayWindow` calls `createTrayWindow` which calls
    // `loadRenderer` synchronously — for a same-tick file:// load,
    // `dom-ready` / `did-finish-load` could fire before we attach
    // listeners on the next microtask. Check the load state first
    // and mark immediately if we already missed the event; otherwise
    // attach the `once` listener as usual.
    if (window.webContents.isLoadingMainFrame()) {
      window.webContents.once("dom-ready", () => {
        domReady = mark();
      });
      window.webContents.once("did-finish-load", () => {
        didFinishLoad = mark();
      });
    } else {
      // Already past load — both events fired during construction.
      // Best-effort: mark them at the same instant so spec consumers
      // see a consistent "first paint landed sub-listener-attach" value.
      domReady = mark();
      didFinishLoad = mark();
    }
    window.once("ready-to-show", () => {
      readyToShow = mark();
    });
  }

  // Mirror showTrayPopoverForE2E's positioning so apples-to-apples
  // with tray-sizing.spec.ts.
  const primary = screen.getPrimaryDisplay();
  const wa = primary.workArea;
  window.setPosition(wa.x + 8, wa.y + 8, false);
  showTrayWindowNow(window);

  let isVisible: number | null = null;
  const deadline = performance.now() + timeoutMs;
  const startedAt = performance.now();
  // In the prewarmed case there's no fresh resize to wait on — the
  // renderer measured during pre-warm and the window is already at
  // its content height. Hold long enough for the OS to swap the off-
  // screen window in and the spec can read back isVisible.
  const minimumPrewarmedHoldMs = 60;
  // The seeded content (if any) must have actually landed before we
  // accept the size as final — see `minStableHeight`. A resize request
  // alone is not readiness: Windows can update getContentSize()
  // synchronously while Chromium's renderer viewport still has the old
  // height for another native event-loop turn. Read renderer innerHeight
  // and require it to acknowledge the CSS-height request. This keeps both
  // possible main-process readback lies (stale 440 and optimistic 688) out
  // of the first-paint contract.
  const resizeRequested = (): boolean =>
    !window.isDestroyed() &&
    lastTrayResizeRequest !== null &&
    lastTrayResizeRequest.dipHeight >= minStableHeight;
  let resizeApplied: number | null = null;
  let finalContentHeight: number | null = null;
  const rendererAppliedResize = async (): Promise<boolean> => {
    if (
      !resizeRequested() ||
      window.isDestroyed() ||
      window.webContents.isDestroyed() ||
      lastTrayResizeRequest === null
    ) {
      return false;
    }
    const request = lastTrayResizeRequest;
    try {
      const rendererHeight = (await window.webContents.executeJavaScript(
        "globalThis.innerHeight",
        true
      )) as unknown;
      if (typeof rendererHeight !== "number" || !Number.isFinite(rendererHeight)) {
        return false;
      }
      finalContentHeight = rendererHeight;
      // innerHeight is expressed in renderer CSS pixels, while Electron's
      // setContentSize and our dipHeight telemetry are in DIP. Compare with
      // the original CSS measurement so this remains correct under zoom.
      if (
        lastTrayResizeRequest === request &&
        Math.abs(rendererHeight - request.cssHeight) <= 1
      ) {
        if (resizeApplied === null) resizeApplied = mark();
        return true;
      }
    } catch {
      // The page may still be navigating. Keep polling until the existing
      // deadline; a permanently unavailable renderer reports timedOut=true.
    }
    return false;
  };
  let timedOut = true;
  while (performance.now() < deadline) {
    if (isVisible === null && !window.isDestroyed() && window.isVisible()) {
      isVisible = mark();
    }
    const applied = await rendererAppliedResize();
    if (mode === "prewarmed") {
      if (
        isVisible !== null &&
        performance.now() - startedAt >= minimumPrewarmedHoldMs &&
        applied
      ) {
        timedOut = false;
        break;
      }
    } else if (
      lastResizeAt > 0 &&
      performance.now() - lastResizeAt >= stableMs &&
      applied
    ) {
      timedOut = false;
      break;
    }
    await new Promise((resolve) => setTimeout(resolve, 10));
  }

  ipcMain.off(TRAY_RESIZE_CHANNEL, probe);

  const stableResize = lastResizeAt > 0 ? Math.round((lastResizeAt - t0) * 100) / 100 : null;
  const mainReportedContentHeight = !window.isDestroyed() ? window.getContentSize()[1] : null;
  const requestedContentHeight = lastTrayResizeRequest?.dipHeight ?? null;
  // Preserve the final renderer truth in timeout diagnostics too. The loop
  // normally populated this while checking the acknowledgement; this last
  // read covers destruction/navigation races where no request was accepted.
  if (!window.isDestroyed() && !window.webContents.isDestroyed()) {
    try {
      const rendererHeight = (await window.webContents.executeJavaScript(
        "globalThis.innerHeight",
        true
      )) as unknown;
      if (typeof rendererHeight === "number" && Number.isFinite(rendererHeight)) {
        finalContentHeight = rendererHeight;
      }
    } catch {
      // A crashed/navigating renderer is reported as null and fails the spec's
      // strict final-height assertion with useful checkpoint context.
    }
  }

  return {
    mode,
    windowCreated,
    domReady,
    didFinishLoad,
    readyToShow,
    isVisible,
    firstResize,
    stableResize,
    resizeApplied,
    finalContentHeight,
    requestedContentHeight,
    mainReportedContentHeight,
    resizeCount,
    timedOut
  };
}

/**
 * Show a single character/number next to the menubar tray icon — used
 * by the Timed (5s) capture flow to render the countdown without
 * popping any window that would steal focus from a menu the user is
 * staging for the shot. `null` clears the title back to icon-only.
 *
 * No-op when the Tray isn't installed (E2E specs that exercise the
 * popover without a real NSStatusItem).
 */
export function setTrayCountdown(text: string | null): void {
  if (tray === null) return;
  setTrayTitleIfSupported(tray, text ?? "");
}

/**
 * `Tray.setTitle` is `@platform darwin` — the label beside the macOS
 * menubar icon.
 *
 * Measured inert rather than fatal off macOS: Windows has called it
 * unconditionally since this code was written and shows nothing, and on
 * Electron 41.10.7 under Linux it returns without throwing. So this guard
 * fixes no crash. What it fixes is the code reading as though the recording
 * dot and the timed countdown were visible on three platforms when they are
 * visible on one — and it names what carries the signal on the other two.
 *
 * Windows telegraphs recording state through the tooltip alone. Linux does
 * the same, plus the menu's own "● Recording — Stop and Save" row, which is
 * why `refreshNativeTrayMenu` runs on every phase change.
 */
function setTrayTitleIfSupported(activeTray: Tray, title: string): void {
  if (process.platform !== "darwin") return;
  activeTray.setTitle(title);
}

/** `mm:ss` since `startedAt`, clamped at zero so a clock skew can't print a
 *  negative duration into a menu label. */
function formatElapsed(startedAt: string): string {
  const elapsedSec = Math.max(
    0,
    Math.floor((Date.now() - new Date(startedAt).getTime()) / 1_000)
  );
  const minutes = Math.floor(elapsedSec / 60).toString().padStart(2, "0");
  const seconds = (elapsedSec % 60).toString().padStart(2, "0");
  return `${minutes}:${seconds}`;
}

export function buildTrayContextMenuTemplate(
  trayBounds?: Electron.Rectangle,
  platform: ShortcutPlatform = shortcutPlatformFromString(process.platform)
): MenuItemConstructorOptions[] {
  // macOS/Windows build this template inside the `right-click` handler, so
  // every read below is fresh. Linux publishes it once via `setContextMenu`
  // and replaces it only when `refreshNativeTrayMenu` runs, so anything that
  // would go stale between republishes has to be left out.
  const menuIsPersistent = traySurfaceForPlatform(platform) === "native-menu";
  const quickCaptureAccelerator = activeTrayAccelerator("quickCapture", platform);
  const videoCaptureAccelerator = activeTrayAccelerator("videoCapture", platform);
  const openLibraryAccelerator = activeTrayAccelerator("openLibrary", platform);
  const recordingState = getRecordingState();
  // Pass the platform through rather than letting this read `process.platform`
  // itself: every other platform-dependent read in this function already comes
  // from the argument, and a function that mixes the two cannot be tested for
  // one platform from a CI host running another — which is the reason
  // `recordingBackendCapabilities` takes the parameter in the first place.
  // Runtime behavior is unchanged; the default argument is `process.platform`.
  const recordingCapabilities = recordingBackendCapabilities(platform);
  const canHostDiscardConfirmation = canRecordingControllerConfirmDiscard();
  // Controls are phase- and backend-aware. In particular, Stop is not shown
  // during the Windows countdown (FFmpeg has not spawned yet), and no action
  // is offered while finalization already owns the backend transition.
  const recordingItems: MenuItemConstructorOptions[] = (() => {
    if (
      recordingState.phase === "recording" &&
      canRunRecordingControl(recordingState, recordingCapabilities, "stop")
    ) {
      // The elapsed clock is only honest on a menu that is rebuilt at the
      // moment it opens. On Linux the menu is a PERSISTENT D-Bus object
      // republished on phase changes, and `phase: "recording"` is set exactly
      // once (recording-service.ts) — there is no per-second tick to hang a
      // rebuild off, and inventing one would replace the menu under a user
      // who has it open. So a persistent menu gets no clock rather than a
      // clock frozen at 00:00. The HUD and the Library both show live time.
      //
      // Not reachable today: `recordingBackendCapabilities("linux")` is
      // `backend: "unsupported"` with every control false, so the `stop`
      // guard above already excludes this whole block on Linux. It is here
      // because the freeze is a property of the PERSISTENT MENU, not of the
      // recorder — whoever lands a Linux recording backend should not have to
      // rediscover it. Pinned by tray-linux-native-menu.test.ts, which mocks
      // a capable Linux backend to reach it.
      const label = menuIsPersistent
        ? "● Recording — Stop and Save"
        : `● Recording ${formatElapsed(recordingState.startedAt)} — Stop and Save`;
      // Top of menu changes while recording — the user almost certainly
      // came here to stop, so make Stop the first item and demote the
      // Capture row. Cancel sits next to Stop so a botched recording
      // can be aborted without persisting a Library row.
      return [
        {
          label,
          click: () => {
            void bus.dispatch("recording:stop", {}, { principal: "ipc" });
          }
        },
        // Both discard the take, so both need a confirmation, and the
        // only legal place to run one mid-take is the HUD (see
        // `confirmDiscardRecording`). The trailing ellipsis is the
        // platform convention for "this asks before it acts" and is
        // load-bearing here: the click arms the HUD rather than
        // discarding anything. If the HUD renderer is gone the items
        // are simply not offered — Stop and Save above always is.
        ...(canHostDiscardConfirmation &&
        canRunRecordingControl(recordingState, recordingCapabilities, "restart")
          ? [
              {
                label: "Restart Recording…",
                click: () => {
                  confirmDiscardRecording("restart");
                }
              } satisfies MenuItemConstructorOptions
            ]
          : []),
        ...(canHostDiscardConfirmation &&
        canRunRecordingControl(recordingState, recordingCapabilities, "cancel")
          ? [
              {
                label: "Cancel Recording…",
                click: () => {
                  confirmDiscardRecording("cancel");
                }
              } satisfies MenuItemConstructorOptions
            ]
          : []),
        { type: "separator" }
      ];
    }
    if (
      (recordingState.phase === "preflight" ||
        recordingState.phase === "countdown" ||
        recordingState.phase === "starting") &&
      canRunRecordingControl(recordingState, recordingCapabilities, "cancel")
    ) {
      return [
        {
          label:
            recordingState.phase === "countdown"
              ? `Cancel recording start (${recordingState.secondsRemaining})`
              : "Cancel recording start",
          click: () => {
            void bus.dispatch("recording:cancel", {}, { principal: "ipc" });
          }
        },
        { type: "separator" }
      ];
    }
    if (recordingState.phase === "stopping" || recordingState.phase === "processing") {
      return [
        {
          label:
            recordingState.phase === "stopping"
              ? "Finalizing recording…"
              : "Processing recording…",
          enabled: false
        },
        { type: "separator" }
      ];
    }
    return [];
  })();
  const baseTemplate: MenuItemConstructorOptions[] = [
    {
      label: "Quick Capture…",
      ...(quickCaptureAccelerator !== null
        ? {
            accelerator: quickCaptureAccelerator,
            // On Windows/Linux Electron otherwise installs a second menu-owned
            // accelerator in addition to PwrSnap's transactional global
            // shortcut. The native menu should display the chord only; macOS
            // retains its native menu accelerator behavior.
            ...(platform !== "darwin" ? { registerAccelerator: false } : {})
          }
        : {}),
      click: () => {
        void dispatchInteractiveCapture("native_tray_menu.quick_capture", "auto");
      }
    },
    {
      // The app's two headline verbs sit together above the rule —
      // snap (Quick Capture) then record (Record Video) — mirroring the
      // tray popover + Library header. No sourceWindowId on a tray
      // dispatch, so the record leaves the Library as a valid target.
      label: "Record Video…",
      // Setup, lead-in, live capture, finalization, and durable failure all
      // belong to the existing attempt. Only idle/ready may open a selector.
      enabled: canStartRecordingAttempt(recordingState),
      ...(videoCaptureAccelerator !== null
        ? {
            accelerator: videoCaptureAccelerator,
            ...(platform !== "darwin" ? { registerAccelerator: false } : {})
          }
        : {}),
      click: () => {
        void bus.dispatch("capture:videoInteractive", {}, { principal: "ipc" });
      }
    },
    { type: "separator" },
    {
      // Same conditional-accelerator treatment as Quick Capture and
      // Record Video above — including `activeTrayAccelerator`, which is
      // what keeps this label honest: it omits the chord unless main
      // currently OWNS that registration, and re-parses the persisted
      // spelling for this platform. Reading `currentTrayHotkeys` raw
      // here would print a chord `globalShortcut.register` refused,
      // which is the same fiction the hard-coded "(⌘⇧L)" tooltip was.
      // `openLibrary` ships unbound, so this usually renders bare.
      label: "Open Library",
      ...(openLibraryAccelerator !== null
        ? {
            accelerator: openLibraryAccelerator,
            ...(platform !== "darwin" ? { registerAccelerator: false } : {})
          }
        : {}),
      click: () => {
        void bus.dispatch("library:focus", {}, { principal: "ipc" });
      }
    },
    {
      label: "Settings…",
      click: () => {
        const options: Parameters<typeof bus.dispatch>[2] = { principal: "ipc" };
        if (trayBounds !== undefined) {
          options.sourceBounds = trayBounds;
        }
        void bus.dispatch("settings:open", {}, options);
      }
    }
  ];
  const extras = extraMenuItems.length > 0
    ? [{ type: "separator" } as MenuItemConstructorOptions, ...extraMenuItems]
    : [];
  return [
    ...recordingItems,
    ...baseTemplate,
    ...extras,
    { type: "separator" },
    {
      label: "Quit PwrSnap",
      click: () => {
        app.quit();
      }
    }
  ];
}

/**
 * Reflect a recording-state transition in the menubar icon. The
 * tooltip + setTitle text both flip while the recorder is active so
 * the user sees the live state without having to open the popover.
 *   - countdown phase → "● 3 / 2 / 1"
 *   - recording phase → "● REC"
 *   - finalizing      → "● …"
 *   - idle/ready/etc. → restore default tooltip + clear title
 *
 * Stays in lock-step with the right-click menu's Recording row
 * (which reads `isRecordingActive()` at popup time) by reacting to
 * the same `subscribeToRecordingState` stream.
 */
function applyRecordingStateToTray(activeTray: Tray, state: RecordingState): void {
  // A phase change rewrites the menu's top rows (Stop / Restart / Cancel,
  // and the disabled "Finalizing…" placeholder). macOS and Windows read the
  // template at right-click time and need nothing here; Linux has to
  // re-publish. Do it first so the menu is already correct if the user gets
  // to it before the tooltip write lands.
  refreshNativeTrayMenu();
  switch (state.phase) {
    case "countdown":
      setTrayTitleIfSupported(activeTray, `● ${state.secondsRemaining}`);
      activeTray.setToolTip(`PwrSnap — recording starts in ${state.secondsRemaining}…`);
      return;
    case "preflight":
      setTrayTitleIfSupported(activeTray, "● …");
      activeTray.setToolTip("PwrSnap — preparing to record");
      return;
    case "starting":
      setTrayTitleIfSupported(activeTray, "● ⋯");
      activeTray.setToolTip("PwrSnap — starting recorder");
      return;
    case "recording":
      setTrayTitleIfSupported(activeTray, "● REC");
      activeTray.setToolTip("PwrSnap — recording. Click the tray and choose Stop.");
      return;
    case "stopping":
      setTrayTitleIfSupported(activeTray, "● ⏳");
      activeTray.setToolTip("PwrSnap — finalizing recording");
      return;
    case "processing":
      setTrayTitleIfSupported(activeTray, "● ⏳");
      activeTray.setToolTip("PwrSnap — processing recording");
      return;
    case "idle":
    case "ready":
    case "failed":
      setTrayTitleIfSupported(activeTray, "");
      activeTray.setToolTip(idleTrayTooltip());
      return;
  }
}
