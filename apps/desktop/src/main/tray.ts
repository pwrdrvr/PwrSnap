// The tray, on all three platforms. TWO SURFACES, not one — see
// `traySurfaceForPlatform` for why the split is forced rather than chosen:
//
//   • macOS + Windows (`popover`): the icon toggles PwrSnap's own
//     BrowserWindow popover, anchored to `tray.getBounds()`; the native
//     Menu is the right-click fallback.
//   • Linux (`native-menu`): the native Menu, attached with
//     `setContextMenu`, is the ONLY surface. `getBounds()`,
//     `popUpContextMenu()` and the `right-click` event are all
//     `@platform darwin,win32`, and Wayland forbids a client positioning
//     its own windows — so there is nothing to anchor a popover to, no
//     gesture to open it with, and nowhere to put it. Also documented in
//     AGENTS.md "The Linux tray is a native menu" and
//     docs/linux-tray-support.md.
//
// Popover-specific behavior, from the Phase 1.7 deepening review:
//   • Real 16×16/@2x template PNG (generated by scripts/generate-tray-icon.mjs
//     from the brand mark SVG). Template images automatically adapt
//     to dark / light / accent menubars — setTitle() text doesn't.
//   • Popover dismiss-on-blur with a 120ms debounce + DevTools open
//     guard + cursor-bounds check, matching Raycast / Linear / Bartender
//     patterns. Avoids the false-positives the original blur-only
//     handler caused (DevTools focus, dragging the popover, focus
//     hopping to a child popover all looked like "click outside").
//   • screen.getDisplayMatching(trayBounds) for multi-display anchoring.
//   • Right-click opens a real Menu (Quit / Open / Settings) — popover
//     is for the rich UI, the native menu is the fallback.

