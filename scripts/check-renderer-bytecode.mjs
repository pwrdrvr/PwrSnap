#!/usr/bin/env node
import { execFileSync, spawn } from "node:child_process";
import { once } from "node:events";
import { globSync, writeFileSync, writeSync } from "node:fs";
import { createRequire } from "node:module";
import { resolve, relative } from "node:path";
import { createInterface } from "node:readline";
import { fileURLToPath } from "node:url";
import { setFlagsFromString } from "node:v8";
import vm from "node:vm";
import { isCliEntrypoint } from "./lib/cli-entrypoint.mjs";

const scriptPath = fileURLToPath(import.meta.url);
const repoRoot = resolve(import.meta.dirname, "..");
export const bytecodeBudget = 48 * 1024;

export function rendererModules(root = repoRoot) {
  return globSync("apps/desktop/src/renderer/src/**/*.{ts,tsx,js,jsx,mjs}", { cwd: root })
    .filter((file) => !/(?:^|\/)(?:__tests__|__fixtures__|fixtures)(?:\/|$)|\.(?:test|spec)\.|\.d\.ts$/.test(file))
    .map((file) => file.replaceAll("\\", "/")).sort();
}

// Vitest 4's module-evaluator wrapper, including its CJS globals. Context
// layout affects bytecode size; a bare module is not the renderer-test oracle.
export function wrapModule(code) {
  const args = [
    "__vite_ssr_exports__", "__vite_ssr_import_meta__", "__vite_ssr_import__",
    "__vite_ssr_dynamic_import__", "__vite_ssr_exportAll__", "__vite_ssr_exportName__",
    "__filename", "__dirname", "module", "exports", "require"
  ];
  return `'use strict';async (${args.join(",")})=>{{${code}\n}}`;
}

async function compileModules() {
  for await (const line of createInterface({ input: process.stdin })) {
    const { file, variant, code, esm } = JSON.parse(line);
    writeSync(1, `@@FILE ${JSON.stringify({ file, variant })}\n`);
    setFlagsFromString("--print-bytecode --print-bytecode-filter=*");
    try {
      // Never run the script or application imports. --no-lazy compiles even
      // uncalled, nested and anonymous functions in this disposable process.
      if (esm) new vm.SourceTextModule(code, { identifier: file });
      else new vm.Script(code, { filename: file });
    } finally {
      setFlagsFromString("--no-print-bytecode");
    }
  }
}

export async function measureModules(modules) {
  const child = spawn(process.execPath, ["--no-lazy", "--no-compilation-cache", "--experimental-vm-modules", scriptPath, "--compile"], {
    cwd: repoRoot, stdio: ["pipe", "pipe", "pipe"]
  });
  const finished = once(child, "close");
  // A syntax error may close the compiler while its next module is being
  // transformed. Report its exit/stderr instead of an unhandled EPIPE.
  child.stdin.on("error", () => {});
  let diagnostics = "";
  child.stderr.on("data", (chunk) => { diagnostics = (diagnostics + chunk).slice(-4000); });
  const records = [];
  let file, variant, name, ordinal;
  const output = createInterface({ input: child.stdout });
  output.on("line", (line) => {
    if (line.startsWith("@@FILE ")) {
      ({ file, variant } = JSON.parse(line.slice(7)));
      ordinal = 0;
    }
    else if (line.startsWith("[generated bytecode for function: ")) {
      name = /^\[generated bytecode for function: (.*?) \(0x/.exec(line)?.[1];
    } else if (file && line.startsWith("Bytecode length: ")) {
      records.push({ file, variant, name: name || "(anonymous)", ordinal: ++ordinal, bytes: Number(line.slice(17)) });
    }
  });
  try {
    for await (const module of modules) {
      if (!child.stdin.write(JSON.stringify(module) + "\n")) await once(child.stdin, "drain");
    }
    child.stdin.end();
    const [exitCode] = await finished;
    if (exitCode !== 0) throw new Error(`Bytecode compiler exited ${exitCode}: ${diagnostics}`);
    return records;
  } finally {
    if (child.exitCode === null) child.kill();
  }
}

async function* transformedModules(context, files) {
  const project = context.projects.find((entry) => entry.name === "desktop-renderer");
  const environment = project?.vite.environments.ssr;
  if (!environment) throw new Error("The desktop-renderer SSR environment is missing");
  const desktopRequire = createRequire(resolve(repoRoot, "apps/desktop/package.json"));
  const { fetchModule } = await import(desktopRequire.resolve("vite"));
  for (const file of files) {
    // jsdom tests run in Vitest's client environment; SSR covers the Node
    // transform too. Both receive the same real module-evaluator wrapper.
    for (const [variant, env] of [["Vitest-client", project.vite.environments.client], ["Vitest-SSR", environment]]) {
      const result = await fetchModule(env, resolve(repoRoot, file), undefined, { inlineSourceMap: false });
      if (!("code" in result)) throw new Error(`No transformed code for ${file} (${variant})`);
      yield { file, variant, code: wrapModule(result.code) };
    }
  }
}

async function* appModules(files) {
  // Resolve tools from the desktop package that declares them, not a root
  // hoist or a dependency owned by another worktree.
  const desktopRoot = resolve(repoRoot, "apps/desktop");
  const desktopRequire = createRequire(resolve(desktopRoot, "package.json"));
  const vite = await import(desktopRequire.resolve("vite"));
  const electronVite = await import(desktopRequire.resolve("electron-vite"));
  const options = { root: desktopRoot, configFile: resolve(desktopRoot, "electron.vite.config.ts") };
  const devConfig = (await electronVite.resolveConfig({ ...options }, "serve", "development")).config?.renderer;
  if (!devConfig) throw new Error("Renderer development configuration is missing");
  const server = await vite.createServer(vite.mergeConfig(devConfig, {
    configFile: false, server: { middlewareMode: true, watch: null, ws: false },
    optimizeDeps: { noDiscovery: true, include: [] }, logLevel: "error"
  }));
  try {
    for (const file of files) {
      const result = await server.transformRequest(`/@fs/${resolve(repoRoot, file).replaceAll("\\", "/")}`);
      if (!result) throw new Error(`No development transform for ${file}`);
      yield { file, variant: "development", code: result.code, esm: true };
    }
  } finally {
    await server.close();
  }
  const buildConfig = (await electronVite.resolveConfig({ ...options }, "build", "production")).config?.renderer;
  if (!buildConfig) throw new Error("Renderer production configuration is missing");
  // Real production React/Rollup/esbuild pipeline, with each application
  // module as an entry. External imports keep third-party code out of this
  // app-owned budget. This is per-module coverage, not final chunk coverage.
  const bundles = await vite.build({
    ...buildConfig, configFile: false, logLevel: "error",
    build: { ...buildConfig.build, write: false, sourcemap: false, emptyOutDir: false,
      rollupOptions: {
        ...buildConfig.build?.rollupOptions,
        input: Object.fromEntries(files.map((file, index) => [`module-${index}`, resolve(repoRoot, file)])),
        external: (_id, importer) => Boolean(importer),
        preserveEntrySignatures: "strict"
      }
    }
  });
  for (const bundle of Array.isArray(bundles) ? bundles : [bundles]) {
    for (const chunk of bundle.output) {
      if (chunk.type !== "chunk" || !chunk.facadeModuleId) continue;
      const file = relative(repoRoot, chunk.facadeModuleId).replaceAll("\\", "/");
      yield { file, variant: "production", code: chunk.code, esm: true };
    }
  }
}

export function overBudget(records) {
  return records.filter((record) => !Number.isInteger(record.bytes) || record.bytes > bytecodeBudget);
}

async function checkBytecode() {
  const v8Options = execFileSync(process.execPath, ["--v8-options"], { encoding: "utf8", maxBuffer: 1024 * 1024 });
  const optimizationLimit = Number(/default: --max-optimized-bytecode-size=(\d+)/.exec(v8Options)?.[1]);
  if (!Number.isInteger(optimizationLimit) || optimizationLimit < bytecodeBudget + 12 * 1024) {
    throw new Error(`Cannot establish 12 KiB of V8 optimization headroom: runtime limit ${optimizationLimit}, budget ${bytecodeBudget}`);
  }
  console.log(`Node ${process.versions.node}, V8 ${process.versions.v8}: function limit ${bytecodeBudget}, TurboFan limit ${optimizationLimit} bytes`);
  const { createVitest } = await import("vitest/node");
  const context = await createVitest("test", {
    root: repoRoot, config: resolve(repoRoot, "vitest.workspace.ts"),
    project: ["desktop-renderer"], watch: false
  });
  const nodeEnv = process.env.NODE_ENV;
  try {
    await context.standalone();
    const files = rendererModules();
    if (!files.length) throw new Error("No renderer modules discovered");
    const modules = async function* () {
      yield* transformedModules(context, files);
      yield* appModules(files);
    };
    const records = await measureModules(modules());
    const reportIndex = process.argv.indexOf("--report");
    if (reportIndex !== -1) writeFileSync(process.argv[reportIndex + 1], JSON.stringify({ versions: process.versions, budget: bytecodeBudget, optimizationLimit, files, records }, null, 2) + "\n");
    for (const file of files) {
      for (const variant of ["Vitest-client", "Vitest-SSR", "development", "production"]) {
        if (!records.some((record) => record.file === file && record.variant === variant)) {
          throw new Error(`V8 reported no functions for ${file} (${variant})`);
        }
      }
    }
    for (const record of [...records].sort((a, b) => b.bytes - a.bytes).slice(0, 15)) {
      console.log(`${record.file}: ${record.name} (${record.variant}) ${record.bytes} bytes`);
    }
    for (const record of overBudget(records)) {
      console.error(`${record.file}: ${record.name} [function ${record.ordinal}] (${record.variant}) uses ${record.bytes} bytes (limit ${bytecodeBudget})`);
    }
    if (overBudget(records).length) throw new Error(`${overBudget(records).length} functions exceed the ${bytecodeBudget}-byte budget`);
    console.log(`Renderer bytecode budget passed: ${files.length} modules, ${records.length} functions`);
  } finally {
    await context.close();
    if (nodeEnv === undefined) delete process.env.NODE_ENV;
    else process.env.NODE_ENV = nodeEnv;
  }
}

if (isCliEntrypoint(import.meta.url)) {
  try {
    if (process.argv[2] === "--compile") await compileModules();
    else await checkBytecode();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
